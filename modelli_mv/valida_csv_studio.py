"""Verify every external CSV against its recorded out-of-fold probabilities.

This is a read-only check of models, probabilities and exported predictions;
only the optional JSON report is written. It never reads the target match or
its public ground truth, fits a model, calibrates a decoder or rewrites a CSV.
"""
import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd

import augmentation_realiste as A
import studio_augmentation as S


def validate_one_csv(path, expected_sha256, probabilities, period, no_data, params):
    """Require the exact CSV generated by these probabilities and this decoder."""
    path = Path(path)
    actual_sha256 = S.P._sha256(path)
    if actual_sha256 != expected_sha256:
        raise ValueError(f'Impronta CSV diversa dal report: {path}')
    probabilities = np.asarray(probabilities)
    period, no_data = np.asarray(period), np.asarray(no_data)
    if (period.ndim != 1 or no_data.shape != period.shape or not len(period)
            or probabilities.shape != (len(period), 3)
            or not np.isfinite(probabilities).all()
            or (probabilities < 0).any() or (probabilities > 1).any()
            or not np.allclose(probabilities.sum(axis=1), 1, rtol=0, atol=5e-4)):
        raise ValueError(f'Probabilità o metadati non validi: {path}')
    codes = S.M.decode(probabilities, period, no_data, params)
    expected = pd.DataFrame({'frame': np.arange(len(codes)), 'label': S.R.LETTERS[codes]})
    actual = pd.read_csv(path)
    if (list(actual.columns) != ['frame', 'label'] or len(actual) != len(expected)
            or not np.array_equal(actual['frame'].to_numpy(), expected['frame'].to_numpy())
            or not np.array_equal(actual['label'].to_numpy(), expected['label'].to_numpy())):
        raise ValueError(f'Frame o etichette CSV diversi dalla decodifica: {path}')
    # R._write_csv uses UTF-8 and LF. Recreate its bytes in memory, without
    # mutating the submission being checked or calling its CSV writer.
    regenerated = expected.to_csv(index=False, lineterminator='\n').encode('utf-8')
    regenerated_sha256 = hashlib.sha256(regenerated).hexdigest()
    if regenerated_sha256 != actual_sha256:
        raise ValueError(f'CSV non riprodotto byte per byte: {path}')
    return {'ok': True, 'rows': len(actual), 'sha256': actual_sha256,
            'decoded_sha256': regenerated_sha256, 'reproduced_identically': True}


def validate_exported_csv(root):
    """Check all main replicates and all preregistered component ablations."""
    root = Path(root)
    config = S.read_json(root / 'config.json')
    plan = S.read_json(root / 'piano.json')
    if (config['smoke'] or config['sources'] != S.source_hashes()
            or config['seeds'] != list(S.REPLICATE_SEEDS)
            or config['ablations'] != list(S.ABLATIONS)
            or config['ablation_decoder'] != 'nested_base_same_fold'):
        raise ValueError('Configurazione incompleta, smoke o codice modificato')
    S.Q.validate_plan(plan)
    items = [tuple(it) for it in plan['items']]
    if (config['original_inputs'] != {'/'.join(it): S.dati.input_hash(it) for it in items}
            or config['clean_and_dirty_inputs'] != {
                '/'.join(it): A.input_manifest(it, labels=True) for it in items}):
        raise ValueError('Input esterni diversi dalla configurazione registrata')
    S.verify_complete(root, config, plan)
    expected_reports = {(mode, rep) for mode in S.MODES for rep in range(len(config['seeds']))}
    expected_reports.update((f'ab_{name}', 0) for name in config['ablations'])
    paths = sorted((root / 'scores').glob('*.json'))
    reports = [S.read_json(path) for path in paths]
    found = [(r['mode'], r['replicate']) for r in reports]
    if len(found) != len(set(found)) or set(found) != expected_reports:
        raise ValueError('Copertura report incompleta, duplicata o inattesa')
    # Store only external frame metadata, not the feature tables of all games.
    meta = {}
    for item in items:
        if item[0] in S.K.DM:
            frame = S.load_original(item)
            if not np.array_equal(frame['frame'].to_numpy(), np.arange(len(frame))):
                raise ValueError(f'Indice frame originale non valido: {item}')
            meta[item] = (frame['period'].to_numpy().copy(),
                          ((frame['n_casa'] + frame['n_ospiti']).to_numpy() == 0))
    checked = []
    for report in reports:
        S.Q.validate_score_report(plan, report)
        mode, replicate = report['mode'], report['replicate']
        ablation = mode.startswith('ab_')
        expected_name = S.model_name(root, mode, replicate)
        if (report['diagnostic_ablation'] is not ablation
                or report['dashboard_model'] != expected_name):
            raise ValueError('Nome o provenienza del report non coerente')
        report_rows = {(row['source'], row['match']): row for row in report['rows']}
        destination = Path(S.R.EXT_RESULTS) / expected_name
        if {p.name for p in destination.glob('*.csv')} != {f'{it[1]}.csv' for it in meta}:
            raise ValueError(f'Copertura CSV incompleta o inattesa: {destination}')
        for outer in plan['outer']:
            key = outer['refit']
            S.verify_fit(root, plan, mode, replicate, key)
            decoder_mode = 'base' if ablation else mode
            params = S.checked_decoder(root, plan, decoder_mode, replicate, outer)
            if params != report['decoders'][str(outer['fold'])]:
                raise ValueError('Decoder del report diverso dal decoder verificato')
            predictions_path = S.fit_path(root, mode, replicate, key) / 'probabilita.npz'
            predictions = S.load_probabilities(predictions_path)
            if set(predictions) != {tuple(it) for it in outer['test']}:
                raise ValueError('Copertura probabilità del fold non valida')
            for item in map(tuple, outer['test']):
                if item not in meta:
                    continue
                period, no_data = meta[item]
                path = destination / f'{item[1]}.csv'
                result = validate_one_csv(path, report_rows[item]['csv_sha256'],
                                          predictions[item], period, no_data, params)
                checked.append(dict(model=expected_name, source=item[0], match=item[1],
                                    fold=outer['fold'], decoder_mode=decoder_mode, **result))
        print(f'CSV EXACT {expected_name}: {len(meta)}', flush=True)
    expected_count = len(expected_reports) * len(meta)
    if len(checked) != expected_count:
        raise ValueError('Numero finale dei CSV verificati non valido')
    return {'ok': True, 'models_checked': len(reports), 'expected_csv': expected_count,
            'csv_checked': len(checked), 'rows_checked': sum(row['rows'] for row in checked),
            'method': 'Exact frames, labels and bytes from saved OOF probabilities and verified nested decoders',
            'public_ground_truth_read': False, 'source_hashes': S.source_hashes(),
            'validator_sha256': S.P._sha256(Path(__file__)), 'csv': checked}


def verify_final_lock(root, *, expected_snapshot=None):
    """Verify both frozen final models and CSVs, before or after public scoring.

    Pass the returned dictionary back as ``expected_snapshot`` after scoring
    to require unchanged model manifests, CSVs, lock and validation report.
    No public labels are read by this function.
    """
    root = Path(root)
    lock_path = root / 'modelli_fissati_prima_del_pubblico.json'
    validation_path = root / 'validazione.json'
    lock, validation = S.read_json(lock_path), S.read_json(validation_path)
    names = {mode: S.model_name(root, mode, 0) for mode in S.MODES}
    if (set(lock) != set(names) or validation.get('ok') is not True
            or set(validation['models']) != set(names.values())):
        raise ValueError('Blocco o validazione dei modelli finali incompleti')
    models = {}
    for mode, name in names.items():
        model_root = Path(S.R.model_dir(name))
        manifest_path = model_root / 'manifest.json'
        digest = S.P._sha256(manifest_path)
        if lock[mode] != {'name': name, 'manifest_sha256': digest}:
            raise ValueError('Manifest finale diverso dal blocco prima del pubblico')
        S.P._verify_artifacts(model_root, {'artefatti': S.read_json(manifest_path)})
        record = validation['models'][name]
        csv_digest = S.P._sha256(Path(S.R.RESULTS) / f'{name}.csv')
        if (record.get('ok') is not True or record.get('reproduced_identically') is not True
                or record.get('csv_sha256') != csv_digest
                or S.read_json(model_root / 'attesi.json').get('csv_sha256') != csv_digest):
            raise ValueError('CSV finale diverso dal file validato e riprodotto')
        models[name] = {'manifest_sha256': digest, 'csv_sha256': csv_digest}
    snapshot = {'ok': True, 'lock_sha256': S.P._sha256(lock_path),
                'validation_sha256': S.P._sha256(validation_path), 'models': models}
    if expected_snapshot is not None and snapshot != expected_snapshot:
        raise ValueError('Artefatti finali modificati durante il controllo pubblico')
    return snapshot


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--esperimento', required=True)
    args = parser.parse_args()
    if not S.P.valid_name(args.esperimento):
        parser.error('Nome non valido')
    root = Path(S.dati.CACHE) / 'augmentation_runs' / args.esperimento
    result = validate_exported_csv(root)
    S.P._write(root / 'validazione_csv_esatti.json', result)
    print(json.dumps({k: v for k, v in result.items() if k not in ('csv', 'source_hashes')}, indent=2))


if __name__ == '__main__':
    main()
